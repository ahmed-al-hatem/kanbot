/**
 * Copies the <path> data of the icons in DESIGN.md §5.2 from @atlaskit/icon and
 * @atlaskit/icon-lab (devDependencies) into src/components/Icon/icons.ts, so the app
 * ships plain SVG paths instead of the Atlaskit React components (DESIGN §5.1 option b).
 *
 * Run after changing the list below: `npm run icons`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

/** name in the app → package path (`core/<name>`) */
const ICONS = {
  add: '@atlaskit/icon/core/add',
  search: '@atlaskit/icon/core/search',
  backlog: '@atlaskit/icon/core/backlog',
  board: '@atlaskit/icon/core/board',
  sprint: '@atlaskit/icon/core/sprint',
  spaces: '@atlaskit/icon-lab/core/spaces',
  'show-more-horizontal': '@atlaskit/icon/core/show-more-horizontal',
  'chevron-down': '@atlaskit/icon/core/chevron-down',
  cross: '@atlaskit/icon/core/cross',
  'drag-handle-vertical': '@atlaskit/icon/core/drag-handle-vertical',
  'check-mark': '@atlaskit/icon/core/check-mark',
  'check-circle': '@atlaskit/icon/core/check-circle',
  calendar: '@atlaskit/icon/core/calendar',
  'log-out': '@atlaskit/icon/core/log-out',
  theme: '@atlaskit/icon/core/theme',
  'ai-sparkle': '@atlaskit/icon/core/ai-sparkle',
  delete: '@atlaskit/icon/core/delete',
  send: '@atlaskit/icon/core/send',
  refresh: '@atlaskit/icon/core/refresh',
  lightbulb: '@atlaskit/icon/core/lightbulb',
  'status-error': '@atlaskit/icon/core/status-error',
  'status-warning': '@atlaskit/icon/core/status-warning',
  'warning-outline': '@atlaskit/icon-lab/core/warning-outline',
  'arrow-right': '@atlaskit/icon/core/arrow-right',
  'arrow-left': '@atlaskit/icon/core/arrow-left',
  'priority-highest': '@atlaskit/icon/core/priority-highest',
  'priority-high': '@atlaskit/icon/core/priority-high',
  'priority-medium': '@atlaskit/icon/core/priority-medium',
  'priority-low': '@atlaskit/icon/core/priority-low',
  bug: '@atlaskit/icon/core/bug',
  pencil: '@atlaskit/icon-lab/core/pencil',
  menu: '@atlaskit/icon/core/menu',
  copy: '@atlaskit/icon/core/copy',
  email: '@atlaskit/icon/core/email',
  'lock-locked': '@atlaskit/icon/core/lock-locked',
  // Language switcher (RTL & Arabic, PR R1): the canvas's globe.
  globe: '@atlaskit/icon/core/globe',
};

const GLYPH = /dangerouslySetGlyph:\s*`([^`]*)`/;
const PATH = /<path\b([^>]*)\/>/g;
const attr = (attrs, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(attrs)?.[1];

const entries = Object.entries(ICONS).map(([name, pkg]) => {
  const source = readFileSync(require.resolve(`${pkg}.js`), 'utf8');
  const glyph = GLYPH.exec(source)?.[1];
  if (!glyph) throw new Error(`No glyph found in ${pkg}`);
  if (/<(?!path\b|\/)/.test(glyph)) throw new Error(`${pkg} has non-path elements`);

  const paths = [...glyph.matchAll(PATH)].map(([, attrs]) => {
    const d = attr(attrs, 'd');
    if (!d) throw new Error(`Path without "d" in ${pkg}`);
    return attr(attrs, 'fill-rule') === 'evenodd' ? { d, evenOdd: true } : { d };
  });
  return [name, paths];
});

const pkgVersion = (name) => require(`${name}/package.json`).version;
const body = entries
  .map(([name, paths]) => {
    const items = paths
      .map((p) => `    { d: '${p.d}'${p.evenOdd ? ', evenOdd: true' : ''} },`)
      .join('\n');
    return `  '${name}': [\n${items}\n  ],`;
  })
  .join('\n');

const out = `/**
 * GENERATED by scripts/extract-icons.mjs — do not edit by hand (run \`npm run icons\`).
 * Source: @atlaskit/icon@${pkgVersion('@atlaskit/icon')}, @atlaskit/icon-lab@${pkgVersion('@atlaskit/icon-lab')} (16×16 viewBox).
 */

export interface IconPath {
  readonly d: string;
  readonly evenOdd?: boolean;
}

export const icons = {
${body}
} as const satisfies Record<string, readonly IconPath[]>;

export type IconName = keyof typeof icons;
`;

const target = fileURLToPath(new URL('../src/components/Icon/icons.ts', import.meta.url));
writeFileSync(target, out);
console.log(`Wrote ${entries.length} icons to src/components/Icon/icons.ts`);
